# 從卡片腳本（CardData.txt、CommonEffects）抓出對戰中會顯示的提示文字（Question、Message、選角色的說明…）
# 扣掉翻譯檔裡已經有的，存成 prompts_queue.json，之後分批翻譯
# 用法：python extract_prompts.py [模擬器路徑]
import glob, json, os, re, sys, collections
D = os.path.dirname(os.path.abspath(__file__))
SIM = sys.argv[1] if len(sys.argv) > 1 else r'C:\Users\Gary\Desktop\WS模擬器'

# 指令後面直接接文字
PLAIN = {'Question', 'Question_Obvious', 'OpponentQuestion', 'OpponentQuestion_Obvious', 'Message', 'OpponentMessage',
         'ChooseCharacterFromTargets', 'ChooseCharacterFromTargets_Optional', 'OpponentChooseCharacterFromTargets',
         'ResolveInAnyOrder', 'AskToUse', 'ChooseCard'}
# 指令後面先接兩個數字再接文字
NUM2 = {'ChooseCharactersFromTargets', 'OpponentChooseCharactersFromTargets', 'ChooseNumber', 'NumberQuestion'}
# 用 | 分隔的多個選項
PIPE = {'MultipleChoiceQuestion', 'CostOptions'}


def prompts():
    files = glob.glob(os.path.join(SIM, 'CardContent', 'Cards', '**', 'CardData.txt'), recursive=True)
    files.append(os.path.join(SIM, 'Weiss Schwarz_Data', 'StreamingAssets', 'CommonEffects_USER_REFERENCE.txt'))
    cnt = collections.Counter()
    for f in files:
        for line in open(f, encoding='utf-8', errors='ignore'):
            s = line.split('//', 1)[0].strip()
            m = re.match(r'^(\w+)\s+(.+)$', s)
            if not m: continue
            k, rest = m.groups()
            if k in PLAIN: parts = [rest]
            elif k in NUM2:
                m2 = re.match(r'^-?\d+\s+-?\d+\s+(.+)$', rest)
                parts = [m2.group(1)] if m2 else []
            elif k in PIPE: parts = rest.split('|')
            else: continue
            for p in parts:
                p = p.strip()
                if re.search(r'[A-Za-z]{2,}', p): cnt[p] += 1
    return cnt


def existing():
    have = set()
    p = os.path.join(SIM, 'AutoTranslator', 'Translation', 'tw', 'Text', '_AutoGeneratedTranslations.txt')
    for line in open(p, encoding='utf-8-sig'):
        m = re.match(r'^((?:[^=\\]|\\.)*)=', line)
        if m and not line.startswith(('r:', 'sr:', '//')):
            have.add(m.group(1).replace('\\=', '=').replace('\\n', '\n'))
    return have


if __name__ == '__main__':
    cnt = prompts()
    have = existing()
    todo = [t for t, n in cnt.most_common() if t not in have]
    json.dump(todo, open(os.path.join(D, 'prompts_queue.json'), 'w', encoding='utf-8'), ensure_ascii=False, indent=0)
    print('distinct', len(cnt), 'already', len(cnt) - len(todo), 'todo', len(todo), 'chars', sum(len(t) for t in todo))
